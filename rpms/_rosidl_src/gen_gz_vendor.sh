#!/usr/bin/env bash
# gen_gz_vendor.sh NAME VER VENDOR_REPO SRC_URL ARCH SUMMARY BR REQ
# Generates an offline gz_*_vendor spec: stages the upstream tarball (Source1),
# pre-applies the vendor's patches, and rewires ament_vendor() to VCS_TYPE path
# (local SOURCE_DIR, no git clone) so it builds in mock with no network.
set -euo pipefail
NAME="$1"; VER="$2"; VREPO="$3"; SRCURL="$4"; ARCH="$5"; SUMMARY="$6"; BR="$7"; REQ="$8"
RPMS_DIR="${RPMS_DIR:-$HOME/hummingbird-rpms/rpms}"
vpkg="$(basename "$VREPO")"
dir="$RPMS_DIR/$NAME"; spec="$dir/$NAME.spec"; mkdir -p "$dir"
{
echo "Name:           $NAME"
echo "Version:        $VER"
echo "Release:        1%{?dist}"
echo "Summary:        $SUMMARY"
echo ""
echo "License:        Apache-2.0"
echo "URL:            https://github.com/$VREPO"
echo "Source0:        https://github.com/$VREPO/archive/refs/tags/$VER.tar.gz#/$NAME-$VER.tar.gz"
echo "Source1:        $SRCURL"
echo ""
[ "$ARCH" = noarch ] && { echo "BuildArch:      noarch"; echo ""; }
echo "# Vendor ExternalProject builds install prebuilt .so's; skip RPM debuginfo."
echo "%global debug_package %{nil}"
echo ""
echo "BuildRequires:  cmake"
echo "BuildRequires:  gcc-c++"
echo "BuildRequires:  make"
echo "BuildRequires:  git"
echo "BuildRequires:  patch"
echo "BuildRequires:  patchelf"
echo "BuildRequires:  pkgconf-pkg-config"
echo "BuildRequires:  python3-devel"
echo "BuildRequires:  python3-colcon-common-extensions"
echo "BuildRequires:  python3-catkin_pkg"
echo "BuildRequires:  python-unversioned-command"
echo "BuildRequires:  ros-jazzy-ament-cmake"
echo "BuildRequires:  ros-jazzy-ament-cmake-vendor-package"
echo "BuildRequires:  ros-jazzy-ament-package"
for d in $BR; do echo "BuildRequires:  $d"; done
echo ""
echo "Requires:       ros-jazzy-ament-package"
for d in $REQ; do echo "Requires:       $d"; done
echo ""
echo "%description"
echo "$SUMMARY Part of the Gazebo simulation stack for ROS 2 Jazzy, under %{_libdir}/ros-jazzy."
echo ""
echo "%prep"
echo "%autosetup -n $vpkg-$VER"
echo "# Offline vendoring: stage upstream, pre-apply vendor patches, rewire"
echo "# ament_vendor() to VCS_TYPE path (local source, no network clone in mock)."
echo "tar -xzf %{SOURCE1} -C %{_builddir}"
echo "_gzsrc=\"%{_builddir}/\$(tar tzf %{SOURCE1} | head -1 | cut -d/ -f1)\""
echo "if [ -d patches ]; then for p in patches/*.patch patches/*.diff; do [ -e \"\$p\" ] && patch -d \"\$_gzsrc\" -p1 < \"\$p\"; done; fi"
echo "sed -i \"s#VCS_URL https://github.com/[^ ]*#VCS_TYPE path\\n  VCS_URL \$_gzsrc#\" CMakeLists.txt"
echo "sed -i \"/^  PATCHES\$/{N;d}\" CMakeLists.txt    # multiline PATCHES form (e.g. ogre-next)"
echo "sed -i \"/^  PATCHES patches\$/d\" CMakeLists.txt  # inline PATCHES form (e.g. dartsim/rendering)"
echo "# POC: DART physics engine omitted (fcl missing in Fedora 44); drop the hard"
echo "# gz_dartsim_vendor requirement so gz-physics builds its bullet + TPE engines."
echo "sed -i \"/find_package(gz_dartsim_vendor REQUIRED)/d\" CMakeLists.txt"
echo "sed -i \"/^  gz_dartsim_vendor\$/d\" CMakeLists.txt"
echo "# POC: GUI omitted (Fedora Qt5 needs icu77, Hummingbird base ships icu78);"
echo "# drop the hard gz_gui_vendor requirement so gz-sim builds headless (server)."
echo "sed -i \"/find_package(gz_gui_vendor REQUIRED)/d\" CMakeLists.txt"
echo "sed -i \"/^  gz_gui_vendor\$/d\" CMakeLists.txt"
echo "grep -n -A6 \"ament_vendor(\" CMakeLists.txt || :"
echo ""
echo "%build"
echo ""
echo "%install"
echo "_manifest=\"\$PWD/%{name}.files\""
echo "export PYTHONUNBUFFERED=1"
echo "# gz libs bake CMAKE_INSTALL_PREFIX (which includes the buildroot) into the"
echo "# .so as a resource/descriptor fallback path; runtime uses the GZ_*/ament env"
echo "# hooks instead. Skip rpmbuild's buildroot-path check for these vendor libs."
echo "export QA_SKIP_BUILD_ROOT=1"
echo "source %{_libdir}/ros-jazzy/setup.bash"
echo ""
echo "colcon build \\"
echo "    --merge-install \\"
echo "    --cmake-args -DPYTHON_EXECUTABLE=\"%{__python3}\" -DCMAKE_BUILD_TYPE=Release \\"
echo "    -DBUILD_TESTING=OFF \\"
echo "    --base-paths . \\"
echo "    --install-base %{buildroot}%{_libdir}/ros-jazzy/ \\"
echo "    --packages-select $vpkg"
echo ""
echo "find %{buildroot}%{_libdir}/ros-jazzy/ -type f ! -name '*.so*' \\"
echo "    -exec sh -c 'file \"\$1\" | grep -q text && sed -i \"s:%{buildroot}::g\" \"\$1\"' _ {} \\;"
echo "rm -rf %{buildroot}%{_libdir}/ros-jazzy/{.catkin,.rosinstall,_setup*,local_setup*,setup*,env.sh,.colcon_install_layout,COLCON_IGNORE,_local_setup*}"
echo "find %{buildroot} -type d -name '__pycache__' -exec rm -rf {} +"
echo "# Strip the buildroot RPATH the vendor ExternalProject bakes into its .so's"
echo "# (else rpmbuild check-buildroot aborts). Keep only rpaths under %{_libdir}."
echo "find %{buildroot}%{_libdir}/ros-jazzy/ -name '*.so*' -type f \\"
echo "    -exec patchelf --shrink-rpath --allowed-rpath-prefixes %{_libdir} {} \\; 2>/dev/null || :"
echo ""
echo "cd %{buildroot}%{_libdir}/ros-jazzy"
echo "find . -mindepth 1 \\( -type f -o -type l \\) -printf '%{_libdir}/ros-jazzy/%%P\\n' > \"\$_manifest\""
echo "find . -mindepth 1 -type d \\"
echo "    ! -path './lib' ! -path './lib/python%{python3_version}' ! -path './lib/python%{python3_version}/site-packages' \\"
echo "    ! -path './share' ! -path './share/ament_index' ! -path './share/ament_index/resource_index' \\"
echo "    ! -path './share/ament_index/resource_index/packages' ! -path './share/ament_index/resource_index/package_run_dependencies' \\"
echo "    ! -path './share/ament_index/resource_index/parent_prefix_path' ! -path './share/colcon-core' ! -path './share/colcon-core/packages' \\"
echo "    -printf '%%%%dir %{_libdir}/ros-jazzy/%%P\\n' >> \"\$_manifest\""
echo "cd - >/dev/null"
echo ""
echo "%files -f %{name}.files"
echo ""
echo "%changelog"
echo "%autochangelog"
} > "$spec"
printf '* Wed Oct 15 2026 Xieshen Zhang <xiezhang@redhat.com> - %s-1\n- Initial Hummingbird gz vendor package (offline VCS_TYPE path build).\n' "$VER" > "$dir/changelog"
echo "wrote $spec"
